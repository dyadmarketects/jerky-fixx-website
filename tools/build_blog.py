def title_with_box(title, box=None):
    t = title
    if box and t.endswith(box):
        plain = t[: -len(box)].rstrip()
    else:
        parts = t.rsplit(" ", 1)
        plain, box = (parts[0], parts[1]) if len(parts) == 2 else ("", t)
    pre = '<span class="bl-t1">%s</span> ' % esc(plain) if plain else ""
    return '%s<em class="lg-box">%s</em>' % (pre, esc(box))


