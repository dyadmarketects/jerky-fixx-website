class Scan(HTMLParser):
    VOID = {"meta", "link", "img", "br", "hr", "input", "source", "area", "base", "col", "embed", "wbr", "track", "param"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack, self.errors = [], []
        self.h = []
        self.hrefs, self.srcs, self.ids, self.imgs, self.ld = [], [], [], [], []
        self.canon = self.title = None
        self._in = None
        self._buf = ""
        self.meta = {}

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag not in self.VOID:
            self.stack.append(tag)
        if tag in ("h1", "h2", "h3", "h4"):
            self.h.append(int(tag[1]))
        if "id" in a:
            self.ids.append(a["id"])
        if tag == "a" and "href" in a:
            self.hrefs.append(a["href"])
        if tag in ("img", "script", "source") and a.get("src"):
            self.srcs.append(a["src"])
        if tag == "link" and a.get("href"):
            if a.get("rel") == "canonical":
                self.canon = a["href"]
            elif a.get("rel") in ("stylesheet", "icon", "apple-touch-icon", "alternate"):
                self.srcs.append(a["href"])
        if tag == "img":
            self.imgs.append(a)
        if tag == "meta":
            self.meta[a.get("name") or a.get("property") or ""] = a.get("content", "")
        if tag == "title" or (tag == "script" and a.get("type") == "application/ld+json"):
            self._in, self._buf = tag, ""

    def handle_endtag(self, tag):
        if tag in self.VOID:
            return
        if tag == self._in:
            if tag == "title":
                self.title = self._buf
            else:
                self.ld.append(self._buf)
            self._in = None
        if not self.stack or self.stack[-1] != tag:
            self.errors.append("unbalanced </%s> (open: %s)" % (tag, self.stack[-3:]))
            if tag in self.stack:
                while self.stack and self.stack.pop() != tag:
                    pass
        else:
            self.stack.pop()

    def handle_data(self, d):
        if self._in:
            self._buf += d


def resolve(url, cur_dir):
    """Return None if resolvable (or external), else the missing path."""
    if re.match(r"(https?:|mailto:|tel:|data:|javascript:)", url):
        return None
    u = url.split("#")[0].split("?")[0]
    if not u:
        return None
    path = os.path.join(ROOT, u.lstrip("/")) if u.startswith("/") else os.path.join(cur_dir, u)
    if os.path.isdir(path):
        path = os.path.join(path, "index.html")
    return None if os.path.exists(path) else u


def validate(pages, posts):
    problems, rows = [], []
    for path, kind in pages:
        rel = os.path.relpath(path, ROOT)
        s = read(path)
        sc = Scan()
        sc.feed(s)
        sc.close()
        errs = list(sc.errors)
        if sc.stack:
            errs.append("unclosed tags: %s" % sc.stack)
        t, d = (sc.title or "").strip(), sc.meta.get("description", "")
        if len(t) > 60 or not t.endswith("| Jerky Fixx"):
            errs.append("title %d chars / suffix: %r" % (len(t), t))
        if not (140 <= len(d) <= 158):
            errs.append("description is %d chars (need 140-158)" % len(d))
        if sc.h.count(1) != 1:
            errs.append("h1 count = %d" % sc.h.count(1))
        prev = 1
        for lv in sc.h:
            if lv > prev + 1:
                errs.append("heading level skips h%d -> h%d" % (prev, lv))
            prev = lv
        if not sc.canon or not sc.canon.startswith(SITE):
            errs.append("bad canonical")
        if sc.meta.get("robots") != "index, follow":
            errs.append("robots meta")
        for k in ("og:title", "og:description", "og:image", "twitter:card"):
            if not sc.meta.get(k):
                errs.append("missing " + k)
        if kind == "post":
            for k in ("article:published_time", "article:author"):
                if not sc.meta.get(k):
                    errs.append("missing " + k)
            if sc.meta.get("og:type") != "article":
                errs.append("og:type should be article")
        if not sc.ld:
            errs.append("no JSON-LD")
        for blob in sc.ld:
            try:
                json.loads(blob)
            except Exception as e:
                errs.append("JSON-LD invalid: %s" % e)
        dup = sorted({i for i in sc.ids if sc.ids.count(i) > 1})
        if dup:
            errs.append("duplicate ids: %s" % dup)
        cur = os.path.dirname(path)
        missing = sorted({m for m in (resolve(u, cur) for u in sc.hrefs + sc.srcs) if m})
        if missing:
            errs.append("unresolved paths: %s" % missing)
        for im in sc.imgs:
            if "alt" not in im:
                errs.append("img without alt: %s" % im.get("src"))
        if "—" in s or "–" in re.sub(r"<script.*?</script>", "", s, flags=re.S):
            errs.append("contains an em/en dash")
        rows.append((rel, len(t), len(d), sc.h.count(1), len(sc.ld), len(sc.hrefs) + len(sc.srcs), errs))
        problems += ["%s: %s" % (rel, e) for e in errs]
    for p in posts:
        if not (700 <= p["words"] <= 1100):
            problems.append("%s: %d words (need 700-1100)" % (p["file"], p["words"]))
        if "—" in p["md"] or "–" in p["md"]:
            problems.append("%s: dash in body" % p["file"])
        if not os.path.exists(os.path.join(ROOT, p["hero"].lstrip("/"))):
            problems.append("%s: hero image missing" % p["file"])
        if not re.match(r"\d{4}-\d{2}-\d{2}$", p["updated"]):
            problems.append("%s: bad updated date" % p["file"])
    print("\nVALIDATION REPORT")
    print("%-44s %5s %5s %3s %3s %5s  %s" % ("page", "title", "desc", "h1", "ld", "links", "status"))
    for r in rows:
        print("%-44s %5d %5d %3d %3d %5d  %s" % (r[0], r[1], r[2], r[3], r[4], r[5], "OK" if not r[6] else "FAIL"))
    for p in posts:
        print("post %-52s %4d words, %d min read" % (p["slug"], p["words"], p["minutes"]))
    # feed + sitemap well-formedness
    import xml.dom.minidom
    for f in ("blog/feed.xml", "sitemap.xml"):
        try:
            xml.dom.minidom.parse(os.path.join(ROOT, f))
            print("%s: well-formed XML" % f)
        except Exception as e:
            problems.append("%s: %s" % (f, e))
    if problems:
        print("\nPROBLEMS (%d):" % len(problems))
        for p in problems:
            print("  - " + p)
    else:
        print("\nAll checks passed.")
    return not problems


