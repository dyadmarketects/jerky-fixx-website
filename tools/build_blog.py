def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)


# --------------------------------------------------------------------------- helpers
def esc(s):
    return html.escape(s, quote=True)


def slugify(t):
    t = html.unescape(re.sub(r"<.*?>", "", t)).lower()
    return re.sub(r"[^a-z0-9]+", "-", t).strip("-")


def pretty_date(d):
    y, m, dd = d.split("-")
    return "%s %d, %s" % (MONTHS[int(m) - 1], int(dd), y)


def rfc822(d):
    import datetime
    dt = datetime.date(*[int(x) for x in d.split("-")])
    return "%s, %02d %s %d 12:00:00 GMT" % (dt.strftime("%a"), dt.day, dt.strftime("%b"), dt.year)


def webp_size(path):
    """Return (w, h) of a .webp file using only the stdlib."""
    with open(path, "rb") as f:
        d = f.read(40)
    if d[:4] != b"RIFF" or d[8:12] != b"WEBP":
        return None
    k = d[12:16]
    if k == b"VP8 ":
        return (int.from_bytes(d[26:28], "little") & 0x3FFF, int.from_bytes(d[28:30], "little") & 0x3FFF)
    if k == b"VP8L":
        b = d[21:25]
        v = int.from_bytes(b, "little")
        return ((v & 0x3FFF) + 1, ((v >> 14) & 0x3FFF) + 1)
    if k == b"VP8X":
        return (int.from_bytes(d[24:27], "little") + 1, int.from_bytes(d[27:30], "little") + 1)
    return None


def img_dims(src):
    p = os.path.join(ROOT, src.lstrip("/"))
    if p.endswith(".webp") and os.path.exists(p):
        s = webp_size(p)
        if s:
            return 'width="%d" height="%d" ' % s
    return ""


# --------------------------------------------------------------------------- markdown
def inline(s):
    s = html.escape(s, quote=False)

    def link(m):
        txt, url = m.group(1), m.group(2)
        ext = re.match(r"https?://", url) and not url.startswith(SITE + "/")
        attrs = ' target="_blank" rel="noopener"' if ext else ""
        return '<a href="%s"%s>%s</a>' % (url.replace('"', "%22"), attrs, txt)

    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", s)
    return s


def md_blocks(text):
    """Restricted Markdown -> list of (kind, html). Supports ## / ### headings, paragraphs,
    - lists, 1. lists, > quotes, **bold**, *italic*, [links](url)."""
    lines = text.replace("\r\n", "\n").split("\n")
    out, i, n = [], 0, len(lines)
    used = set()

    def starts_block(l):
        return bool(re.match(r"(#{1,6}\s|[-*]\s+|\d+\.\s+|>\s?)", l))

    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        m = re.match(r"(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if m:
            lvl = len(m.group(1))
            if lvl == 1:
                raise ValueError("H1 not allowed in post body (the title is the h1): " + line)
            sid = slugify(m.group(2)) or "section"
            base, k = sid, 2
            while sid in used:
                sid = "%s-%d" % (base, k)
                k += 1
            used.add(sid)
            out.append(("h%d" % lvl, '<h%d id="%s">%s</h%d>' % (lvl, sid, inline(m.group(2)), lvl)))
            i += 1
            continue
        if re.match(r"[-*]\s+", line) or re.match(r"\d+\.\s+", line):
            ordered = bool(re.match(r"\d+\.\s+", line))
            pat = r"\d+\.\s+" if ordered else r"[-*]\s+"
            items = []
            while i < n and re.match(pat, lines[i]):
                buf = [re.sub(pat, "", lines[i], count=1)]
                i += 1
                while i < n and lines[i].strip() and re.match(r"\s{2,}\S", lines[i]):
                    buf.append(lines[i].strip())
                    i += 1
                items.append("<li>%s</li>" % inline(" ".join(buf)))
                while i < n and not lines[i].strip() and i + 1 < n and re.match(pat, lines[i + 1]):
                    i += 1
            tag = "ol" if ordered else "ul"
            out.append((tag, "<%s>\n%s\n</%s>" % (tag, "\n".join(items), tag)))
            continue
        if line.startswith(">"):
            buf = []
            while i < n and lines[i].startswith(">"):
                buf.append(lines[i].lstrip(">").strip())
                i += 1
            out.append(("blockquote", "<blockquote><p>%s</p></blockquote>" % inline(" ".join(buf))))
            continue
        buf = []
        while i < n and lines[i].strip() and not starts_block(lines[i]):
            buf.append(lines[i].strip())
            i += 1
        out.append(("p", "<p>%s</p>" % inline(" ".join(buf))))
    return out


def plain_text(md):
    t = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", md)
    t = re.sub(r"[#*>_`]", " ", t)
    return t


# --------------------------------------------------------------------------- posts
def load_posts():
    posts = []
    if not os.path.isdir(POSTS):
        return posts
    for fn in sorted(os.listdir(POSTS)):
        m = re.match(r"(\d{4}-\d{2}-\d{2})-(.+)\.md$", fn)
        if not m:
            continue
        raw = read(os.path.join(POSTS, fn))
        mm = re.match(r"---\n(.*?)\n---\n(.*)$", raw, re.S)
        if not mm:
            raise SystemExit("%s: missing front matter" % fn)
        fm = {}
        for ln in mm.group(1).split("\n"):
            if ":" in ln and not ln.startswith("#"):
                k, v = ln.split(":", 1)
                fm[k.strip()] = v.strip()
        for req in ("title", "description", "slug", "date", "keywords", "hero_alt", "excerpt"):
            if not fm.get(req):
                raise SystemExit("%s: front matter field '%s' is required" % (fn, req))
        fm.setdefault("updated", fm["date"])
        fm.setdefault("hero", "/img/jerky-fixx-family-booth.webp")
        body = mm.group(2).strip() + "\n"
        fm["file"] = fn
        fm["md"] = body
        fm["words"] = len(plain_text(body).split())
        fm["minutes"] = max(1, int(math.ceil(fm["words"] / 220.0)))
        fm["kw"] = [k.strip() for k in fm["keywords"].split(",") if k.strip()]
        fm["url"] = "/blog/%s/" % fm["slug"]
        fm["abs"] = SITE + fm["url"]
        fm["seo_title"] = fm.get("seo_title") or "%s | Jerky Fixx" % fm["title"]
        posts.append(fm)
    posts.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)
    slugs = [p["slug"] for p in posts]
    if len(set(slugs)) != len(slugs):
        raise SystemExit("duplicate slugs")
    return posts


def related(post, posts, n=3):
    others = [p for p in posts if p["slug"] != post["slug"]]
    kws = set(k.lower() for k in post["kw"])
    others.sort(key=lambda p: (-len(kws & set(k.lower() for k in p["kw"])), -int(p["date"].replace("-", "")), p["slug"]))
    return others[:n]


# --------------------------------------------------------------------------- shared chrome from cart.html
def absu(s):
    s = re.sub(r'(src|href)="img/', r'\1="/img/', s)
    s = s.replace('href="cart.html"', 'href="/cart.html"')
    return s


def grab(src, start, end):
    i = src.index(start)
    j = src.index(end, i) + len(end)
    return src[i:j]


def chrome():
    cart = read(os.path.join(ROOT, "cart.html"))
    index = read(os.path.join(ROOT, "index.html"))
    header = absu(grab(cart, '<header class="site-head"', "</header>"))
    header = header.replace('<a href="/blog/">Blog</a>', '<a href="/blog/" aria-current="page">Blog</a>', 1)
    mnav = absu(grab(cart, '<nav class="mnav"', "</nav>"))
    social = grab(cart, '<aside class="social-tab"', "</aside>")
    tabbar = absu(grab(cart, '<nav class="tabbar"', "</nav>")).replace(' aria-current="page"', "")
    consent = cart[cart.index("<!-- COOKIES -->"):cart.index('<footer class="foot">')].rstrip() + "\n"
    footer = absu(grab(cart, '<footer class="foot">', "</footer>"))
    head = index[:index.index("</head>")]
    favicons = "\n".join(re.findall(r'<link rel="(?:icon|apple-touch-icon)"[^>]*>', head))
    fonts = "\n".join(re.findall(r'<link rel="(?:preconnect|stylesheet)" href="https://fonts[^>]*>', head))
    scripts = ('<script src="/js/shop.js"></script>\n<script>\n(function(){\n'
               '  const tt=document.querySelectorAll(".track");tt.forEach(t=>{t.innerHTML=Array(10).fill("<span>WARNING! FLAVORS MAY CAUSE ADDICTION</span>").join("")});\n'
               '  var tb=document.getElementById("tabbar");if(tb)tb.querySelectorAll("a[aria-current]").forEach(function(a){a.removeAttribute("aria-current")});\n'
               '})();\n</script>')
    return dict(header=header, mnav=mnav, social=social, tabbar=tabbar, consent=consent,
                footer=footer, favicons=favicons, fonts=fonts, scripts=scripts)


