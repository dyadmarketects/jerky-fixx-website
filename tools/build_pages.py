def page_ld(meta, main, fl):
    if meta.get("robots", "").startswith("noindex"):
        return ""
    url = SITE + meta["path"]
    graph = [
        {"@type": "ContactPage" if meta.get("contactpage") else ("FAQPage" if meta.get("faqpage") else "WebPage"),
         "@id": url + "#page", "url": url, "name": meta["title"], "description": meta["description"], "inLanguage": "en-US",
         "isPartOf": {"@id": SITE + "/#site"}, "about": {"@id": ORG_ID}, "breadcrumb": {"@id": url + "#crumbs"}},
        {"@type": "BreadcrumbList", "@id": url + "#crumbs", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE + "/"},
            {"@type": "ListItem", "position": 2, "name": meta["crumb"], "item": url}]},
    ]
    if meta.get("faqpage"):
        qa = []
        for q, a in re.findall(r"<details><summary>(.*?)</summary><p>(.*?)</p></details>", main, re.S):
            text = html.unescape(re.sub(r"<.*?>", "", a)).strip()
            qa.append({"@type": "Question", "name": html.unescape(q).strip(), "acceptedAnswer": {"@type": "Answer", "text": text}})
        graph[0]["mainEntity"] = qa
    if meta.get("products"):
        graph.append(catalog(fl))
    return jsonld({"@context": "https://schema.org", "@graph": graph}) + "\n"


