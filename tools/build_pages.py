def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)


def esc(s):
    return html.escape(s, quote=True)


def grab(src, start, end):
    i = src.index(start)
    j = src.index(end, i) + len(end)
    return src[i:j]


def absu(s):
    s = re.sub(r'(src|href|poster)="(img|vid|css|js)/', r'\1="/\2/', s)
    return s.replace('href="cart.html"', 'href="/cart.html"')


def jsonld(obj):
    s = json.dumps(obj, ensure_ascii=False, indent=1)
    return '<script type="application/ld+json">\n%s\n</script>' % s.replace("</", "<\\/")


# --------------------------------------------------------------------------- data from the site itself
def flavors():
    """FLAVORS from js/shop.js: [(name, heat, description, top_seller)]"""
    src = read(os.path.join(ROOT, "js", "shop.js"))
    block = src[src.index("const FLAVORS=["):src.index("].map(")]
    out = []
    for m in re.finditer(r'\[\s*"([^"]+)",\s*(\d),\s*"([^"]+)"(?:,\s*(1))?\]', block):
        out.append((m.group(1), int(m.group(2)), m.group(3), bool(m.group(4))))
    if len(out) < 20:
        raise SystemExit("could not read FLAVORS from js/shop.js")
    return out


def fslug(n):
    return re.sub(r"^-|-$", "", re.sub(r"[^a-z0-9]+", "-", n.lower().replace("&", "and")))


def chrome():
    cart = read(os.path.join(ROOT, "cart.html"))
    index = read(os.path.join(ROOT, "index.html"))
    head = index[:index.index("</head>")]
    return dict(
        header=absu(grab(cart, '<header class="site-head"', "</header>")),
        mnav=absu(grab(cart, '<nav class="mnav"', "</nav>")),
        social=grab(cart, '<aside class="social-tab"', "</aside>"),
        tabbar=absu(grab(cart, '<nav class="tabbar"', "</nav>")).replace(' aria-current="page"', ""),
        consent=cart[cart.index("<!-- COOKIES -->"):cart.index('<footer class="foot">')].rstrip() + "\n",
        footer=absu(grab(cart, '<footer class="foot">', "</footer>")),
        favicons="\n".join(re.findall(r'<link rel="(?:icon|apple-touch-icon)"[^>]*>', head)),
        fonts="\n".join(re.findall(r'<link rel="(?:preconnect|stylesheet)" href="https://fonts[^>]*>', head)),
        index=index,
    )


def section(index, sid):
    """One <section id=sid> from the home page, minus the 'more on its own page' links."""
    m = re.search(r'<section\b[^>]*\bid="%s"' % re.escape(sid), index)
    if not m:
        raise SystemExit("index.html has no section #" + sid)
    j = index.index("</section>", m.start()) + len("</section>")
    s = index[m.start():j]
    s = re.sub(r'\n?[ \t]*<p class="sec-more">.*?</p>', "", s)
    return absu(s)


def flavors_by_heat(fl):
    groups = [("Mild", "heat 0 to 1", lambda h: h <= 1), ("Medium", "heat 2 to 3", lambda h: 2 <= h <= 3),
              ("Hot", "heat 4", lambda h: h == 4), ("X-Hot", "heat 5", lambda h: h == 5)]
    out = ['<div class="pg-heat">']
    for name, rng, test in groups:
        items = [f for f in fl if test(f[1])]
        lis = "\n".join(
            '        <li><img src="/img/flavors/%s.webp" alt="" width="360" height="360" loading="lazy"><div><h4>%s%s</h4>'
            '<p class="pg-heatline">%d<span aria-hidden="true">/5</span><span class="sr-only"> out of 5</span></p><p>%s</p></div></li>'
            % (fslug(n), esc(n), ' <span class="pg-top">Top seller</span>' if top else "", h, esc(d)) for n, h, d, top in items)
        out.append('  <section class="pg-heatgrp" aria-labelledby="heat-%s">\n    <h3 id="heat-%s">%s <small>%s, %d flavors</small></h3>\n'
                   '    <ul class="pg-flavors">\n%s\n    </ul>\n  </section>' % (fslug(name), fslug(name), name, rng, len(items), lis))
    out.append("</div>")
    return "\n".join(out)


