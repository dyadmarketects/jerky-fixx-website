def parse_source(fn):
    raw = read(os.path.join(SRC, fn))
    m = re.match(r"<!--page\n(.*?)\n-->\n(.*)$", raw, re.S)
    if not m:
        raise SystemExit(fn + ": missing <!--page {json} --> header")
    meta = json.loads(m.group(1))
    body, _, scripts = m.group(2).partition("<!--scripts-->\n")
    return meta, body, scripts


def build_page(C, fn, fl):
    meta, body, scripts = parse_source(fn)
    extra_faq = ""
    mm = re.search(r"<!--extra-faq-->\n(.*?)<!--/extra-faq-->\n?", body, re.S)
    if mm:
        extra_faq = mm.group(1)
        body = body[:mm.start()] + body[mm.end():]

    def sec(m):
        s = section(C["index"], m.group(1))
        if m.group(1) == "faq" and extra_faq:
            k = s.rindex("</details>") + len("</details>")
            s = s[:k] + "\n" + extra_faq.rstrip("\n") + s[k:]
        return s
    body = re.sub(r"\{\{section:([\w-]+)\}\}", sec, body)
    body = body.replace("{{flavors_by_heat}}", flavors_by_heat(fl))
    main = (hero(meta) if meta.get("hero") else "") + body + (CTA if meta.get("cta") else "")
    nav = meta.get("nav")
    out = head(C, meta, page_ld(meta, main, fl)) + f'''<body class="{meta.get("body_class", "lg-page")}">
{MARK % fn}
<a class="skip" href="#main">Skip to content</a>
{mark_current(C["header"], nav)}
{mark_current(C["mnav"], nav)}
{C["social"]}

<main id="main">
{main.rstrip()}
</main>

{C["tabbar"]}

{C["consent"]}
{C["footer"]}

<script src="/js/shop.js"></script>
<script src="/js/sections.js"></script>
{scripts.rstrip()}
</body>
</html>
'''
    return meta, re.sub(r"\n{3,}", "\n\n", out)


def sync_home(C):
    p = os.path.join(ROOT, "index.html")
    s = read(p)
    cart = read(os.path.join(ROOT, "cart.html"))
    nav = absu(grab(cart, '<nav class="nav"', "</nav>"))
    s = s.replace(grab(s, '<nav class="nav"', "</nav>"), mark_current(nav, "/"))
    s = s.replace(grab(s, '<nav class="mnav"', "</nav>"), mark_current(C["mnav"], "/"))
    s = s.replace(grab(s, '<footer class="foot">', "</footer>"), C["footer"])
    s = s[:s.index("<!-- COOKIES -->")] + C["consent"] + "\n" + s[s.index('<footer class="foot">'):]
    a, z = "<!-- JSONLD:START -->", "<!-- JSONLD:END -->"
    s = s[:s.index(a) + len(a)] + "\n" + home_ld() + "\n" + s[s.index(z):]
    return s


def update_sitemap(entries):
    """entries: [(path, changed, changefreq, priority, extra_xml)] for every non-blog page."""
    p = os.path.join(ROOT, "sitemap.xml")
    s = read(p)
    old = dict(re.findall(r"<loc>([^<]+)</loc><lastmod>([^<]+)</lastmod>", s))
    blog = re.findall(r"[ \t]*<url><loc>https://jerkyfixx\.com/blog/.*?</url>\n", s, re.S)
    rows = []
    for path, changed, cf, pr, extra in entries:
        loc = SITE + path
        lm = TODAY if changed or loc not in old else old[loc]
        if extra:
            rows.append(f"  <url><loc>{loc}</loc><lastmod>{lm}</lastmod><changefreq>{cf}</changefreq><priority>{pr}</priority>\n{extra}  </url>\n")
        else:
            rows.append(f"  <url><loc>{loc}</loc><lastmod>{lm}</lastmod><changefreq>{cf}</changefreq><priority>{pr}</priority></url>\n")
    head = s[:s.index("<url>")].rstrip(" ")
    write(p, head + "".join(rows) + "".join(blog) + "</urlset>\n")


def main():
    C = chrome()
    fl = flavors()
    entries = []
    home_new = sync_home(C)
    home_path = os.path.join(ROOT, "index.html")
    home_changed = home_new != read(home_path)
    if home_changed:
        write(home_path, home_new)
    C["index"] = home_new
    entries.append(("/", home_changed, "weekly", "1.0",
                    "    <image:image><image:loc>https://jerkyfixx.com/img/og-image.jpg</image:loc></image:image>\n"
                    "    <image:image><image:loc>https://jerkyfixx.com/img/jerky-fixx-family-booth.webp</image:loc></image:image>\n"))
    built = []
    for fn, out in PAGES:
        meta, page = build_page(C, fn, fl)
        dest = os.path.join(ROOT, out)
        changed = not os.path.exists(dest) or read(dest) != page
        if changed:
            write(dest, page)
        built.append((dest, meta))
        if meta.get("sitemap", True) and not meta.get("robots", "").startswith("noindex"):
            entries.append((meta["path"], changed, meta.get("changefreq", "monthly"), str(meta.get("priority", 0.5)), ""))
    update_sitemap(entries)
    print("Built %d pages, synced index.html chrome and structured data, updated sitemap.xml" % len(built))
    ok = validate(built)
    sys.exit(0 if ok else 1)


# --------------------------------------------------------------------------- validation
def validate(built):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from build_blog import Scan, resolve
    problems = []
    titles, descs = {}, {}
    print("\nVALIDATION REPORT")
    print("%-34s %5s %5s %3s %3s  %s" % ("page", "title", "desc", "h1", "ld", "status"))
    for path, meta in built + [(os.path.join(ROOT, "index.html"), {"path": "/"})]:
        rel = os.path.relpath(path, ROOT)
        s = read(path)
        sc = Scan()
        sc.feed(s)
        sc.close()
        errs = list(sc.errors)
        if sc.stack:
            errs.append("unclosed tags: %s" % sc.stack[-5:])
        t, d = (sc.title or "").strip(), sc.meta.get("description", "")
        noindex = sc.meta.get("robots", "").startswith("noindex")
        if len(t) > 60 or not t.startswith("Jerky Fixx") and not t.endswith("| Jerky Fixx"):
            errs.append("title %d chars: %r" % (len(t), t))
        if not noindex and not (120 <= len(d) <= 158):
            errs.append("description is %d chars" % len(d))
        if t in titles:
            errs.append("duplicate title with " + titles[t])
        if d in descs:
            errs.append("duplicate description with " + descs[d])
        titles[t], descs[d] = rel, rel
        if sc.h.count(1) != 1:
            errs.append("h1 count = %d" % sc.h.count(1))
        prev = 1
        for lv in sc.h:
            if lv > prev + 1:
                errs.append("heading level skips h%d -> h%d" % (prev, lv))
            prev = lv
        if not noindex and (not sc.canon or sc.canon != SITE + meta["path"]):
            errs.append("canonical %r" % sc.canon)
        for k in ("og:title", "og:description", "og:image", "twitter:card"):
            if not sc.meta.get(k):
                errs.append("missing " + k)
        for blob in sc.ld:
            try:
                json.loads(blob)
            except Exception as e:
                errs.append("JSON-LD invalid: %s" % e)
        if not noindex and not sc.ld:
            errs.append("no JSON-LD")
        dup = sorted({i for i in sc.ids if sc.ids.count(i) > 1})
        if dup:
            errs.append("duplicate ids: %s" % dup)
        missing = sorted({m for m in (resolve(u, os.path.dirname(path)) for u in sc.hrefs + sc.srcs if not u.startswith("sms:")) if m})
        if missing:
            errs.append("unresolved paths: %s" % missing)
        for im in sc.imgs:
            if "alt" not in im:
                errs.append("img without alt: %s" % im.get("src"))
        bare = re.sub(r"<script.*?</script>|<!--.*?-->", "", s, flags=re.S)
        if "—" in bare or "–" in bare:
            errs.append("contains an em/en dash")
        print("%-34s %5d %5d %3d %3d  %s" % (rel, len(t), len(d), sc.h.count(1), len(sc.ld), "OK" if not errs else "FAIL"))
        problems += ["%s: %s" % (rel, e) for e in errs]
    import xml.dom.minidom
    try:
        xml.dom.minidom.parse(os.path.join(ROOT, "sitemap.xml"))
        print("sitemap.xml: well-formed XML")
    except Exception as e:
        problems.append("sitemap.xml: %s" % e)
    if problems:
        print("\nPROBLEMS (%d):" % len(problems))
        for p in problems:
            print("  - " + p)
    else:
        print("\nAll checks passed.")
    return not problems


