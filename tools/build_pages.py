#!/usr/bin/env python3
"""Jerky Fixx page builder. Python 3 standard library only.

    python3 tools/build_pages.py          # build, then validate (exits 1 on any problem)
    python3 tools/build_blog.py           # run after this whenever the shared chrome changed

What it does
  * Builds every interior page from a source file in tools/pages/:
      jerky.html          -> /jerky/index.html            our-story.html  -> /our-story/index.html
      the-lab.html        -> /the-lab/index.html          dealer-locator.html -> /dealer-locator/index.html
      vip-club.html       -> /vip-club/index.html         contact.html    -> /contact/index.html
      faq.html            -> /faq/index.html
      privacy.html, terms.html, cookies.html, accessibility.html, 404.html -> same name in the site root
  * Copies the shared chrome (header, mobile menu, social tab, bottom tab bar, cookie banner, footer) from cart.html,
    so cart.html is the one place to edit navigation and footer links. It also syncs the nav, mobile menu,
    footer and cookie banner into index.html (the home page keeps its own in-page tab bar and hero).
  * Pulls home page sections straight out of index.html with {{section:ID}} (for example {{section:menu}}),
    so the menu grid, dealer map, forms, lab video and FAQ have one source of truth.
  * Writes the home page structured data between <!-- JSONLD:START --> and <!-- JSONLD:END --> in index.html,
    a BreadcrumbList on every interior page, Product/Offer data (real names and prices from js/shop.js) on /jerky/,
    and FAQPage data on /faq/ only.
  * Rewrites the non-blog <url> entries in sitemap.xml (tools/build_blog.py owns the /blog/ entries).
    A page's <lastmod> only changes when its HTML actually changed.

Source file format (tools/pages/*.html)
  <!--page {json} -->   title, description, path, crumb, hero, body_class, cta, priority, changefreq ...
  ...HTML for inside <main>, after the generated hero band...
  <!--scripts-->        optional: page-only scripts after the shared ones
Placeholders: {{section:ID}}, {{flavors_by_heat}}. In faq.html, <!--extra-faq--> ... <!--/extra-faq--> holds the
questions that are added to the home page FAQ list.
Never edit the generated HTML by hand. Edit tools/pages/*.html (or cart.html / index.html) and rebuild.
"""
